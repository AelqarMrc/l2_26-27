# Print est une fonction affichant des chaines de caractères sur la sortie standard
# Elle peut prendre cependant d'autres paramètres mais on verra cela plus tard
print('Hello World !!!')

# On peut aussi mettre les éléments les uns à la suite des autres
# Un espace est automatiquement mis (sauf si change ce comportement)
print("Hello", "World", "!!!")
